import { NextResponse } from "next/server";
import { createServerSupabase } from "@/lib/supabase/server";

export async function POST(
  _request: Request,
  context: { params: Promise<{ id: string }> }
) {
  const { id: reportId } = await context.params;
  const supabase = await createServerSupabase();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const { data: report } = await supabase
    .from("reports")
    .select("*")
    .eq("id", reportId)
    .eq("owner_id", user.id)
    .single();

  if (!report) {
    return NextResponse.json({ error: "Report not found or access denied." }, { status: 404 });
  }

  const [{ data: evidence }, { data: assessments }, { data: reviews }, { data: events }] =
    await Promise.all([
      supabase
        .from("evidence")
        .select("id, phase, sha256_hash, width, height, has_pii_flag, created_at")
        .eq("report_id", reportId)
        .order("created_at", { ascending: false }),
      supabase
        .from("assessments")
        .select("id, stage1_model_id, stage2_model_id, prompt_version, structured_output, status, created_at")
        .eq("report_id", reportId)
        .order("created_at", { ascending: false })
        .limit(1),
      supabase
        .from("reviews")
        .select("id, decision, factual_note, created_at")
        .eq("report_id", reportId)
        .order("created_at", { ascending: false })
        .limit(1),
      supabase
        .from("report_events")
        .select("id, event_type, summary, created_at")
        .eq("report_id", reportId)
        .order("created_at", { ascending: true }),
    ]);

  const latestAssessment = assessments?.[0] ?? null;
  const latestReview = reviews?.[0] ?? null;

  const snapshotPayload = {
    generated_at: new Date().toISOString(),
    disclaimer:
      "Independent citizen follow-up packet generated by CivicProof. AI observations are provisional and do not constitute legal conclusions, official municipal submissions, or authenticity certification.",
    report: {
      id: report.id,
      title: report.title,
      category: report.category,
      locality: "GVMC Ward 18 – MVP Colony, Visakhapatnam",
      lat: report.lat,
      lng: report.lng,
      landmark: report.landmark,
      external_ref_id: report.external_ref_id,
      external_status: report.external_status,
      citizen_review: report.citizen_review,
      is_synthetic_demo: report.is_synthetic_demo,
    },
    evidence: evidence ?? [],
    provisional_ai_assessment: latestAssessment,
    citizen_review_record: latestReview,
    timeline: events ?? [],
  };

  const { data: snapshot, error } = await supabase
    .from("export_snapshots")
    .insert({
      report_id: reportId,
      owner_id: user.id,
      prompt_version: latestAssessment?.prompt_version ?? "none",
      snapshot_json: snapshotPayload,
    })
    .select("id, created_at, prompt_version")
    .single();

  if (error || !snapshot) {
    return NextResponse.json({ error: "Failed to record export snapshot." }, { status: 500 });
  }

  await supabase.from("report_events").insert({
    report_id: reportId,
    owner_id: user.id,
    event_type: "packet_exported",
    summary: `Generated Follow-up Evidence Packet snapshot (${snapshot.id.slice(0, 8)}).`,
    metadata: { snapshot_id: snapshot.id, prompt_version: snapshot.prompt_version },
  });

  return NextResponse.json({ snapshot }, { status: 201 });
}